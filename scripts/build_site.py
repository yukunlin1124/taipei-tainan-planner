"""Pack timetables/*.json into site/data.js and refresh the offline cache in site/sw.js
(the CACHE name and the SHELL list of files to keep on the phone).

Run after the timetables change (from anywhere):
    python scripts/build_site.py
"""
import glob
import hashlib
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TIMETABLES = os.path.join(ROOT, "timetables")
SITE = os.path.join(ROOT, "site")

# Every parsed timetable; site/matcher.js picks the ones each direction needs by name.
tables = {}
for path in sorted(glob.glob(os.path.join(TIMETABLES, "*.json"))):
    with open(path, encoding="utf-8") as f:
        tables[os.path.splitext(os.path.basename(path))[0]] = json.load(f)

payload = json.dumps(tables, ensure_ascii=False, separators=(",", ":"))
with open(os.path.join(SITE, "data.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build_site.py from timetables/*.json - do not edit by hand.\n")
    f.write("window.TIMETABLES = " + payload + ";\n")

# Every site file except sw.js is kept offline; the cache name changes whenever any of
# them changes, so installed phones pick up updates.
files = [fn for fn in sorted(os.listdir(SITE))
         if fn != "sw.js" and os.path.isfile(os.path.join(SITE, fn))]
h = hashlib.sha1()
for fn in files:
    with open(os.path.join(SITE, fn), "rb") as f:
        h.update(fn.encode() + f.read())
shell = "const SHELL = [\n" + "".join(f'  "./{fn}",\n' for fn in ["", *files]) + "];"
sw = os.path.join(SITE, "sw.js")
with open(sw, encoding="utf-8") as f:
    src = f.read()
src = re.sub(r'const CACHE = "[^"]*";', f'const CACHE = "planner-{h.hexdigest()[:10]}";', src)
src = re.sub(r"const SHELL = \[[^\]]*\];", lambda m: shell, src)
with open(sw, "w", encoding="utf-8") as f:
    f.write(src)

print("site/data.js:", {k: len(v) for k, v in tables.items()})
